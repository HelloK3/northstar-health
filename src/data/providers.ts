export function getProvider(id: string) {
  return providers.find((p) => p.id === id);
}

export function providerName(p: Pick<Provider, "firstName" | "lastName" | "credentials">) {
  return `Dr. ${p.firstName} ${p.lastName}`;
}

export function allLanguages() {
  return [...new Set(providers.flatMap((p) => p.languages))].sort();
}
